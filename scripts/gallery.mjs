// Screenshots for the README and the Devpost gallery.   node scripts/gallery.mjs
import { chromium } from "playwright-core";
const base = "http://localhost:3000";
const out = "docs/screenshots";
const b = await chromium.launch({ channel: "msedge", headless: true });
const page = await (await b.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1.5 })).newPage();
const shot = (name, full = false) => page.screenshot({ path: `${out}/${name}.png`, fullPage: full });

await page.goto(base, { waitUntil: "networkidle" });
await shot("1-home");
await page.goto(`${base}/snap`, { waitUntil: "networkidle" });
await page.getByRole("button", { name: "Astronaut bunny" }).click();
await page.getByText("License to sell").waitFor({ timeout: 60000 });
await page.waitForTimeout(900);
await shot("2-snap-match", true);
await page.goto(`${base}/agent`, { waitUntil: "networkidle" });
await page.getByRole("button", { name: "Run agent" }).click();
await page.getByText("Answer", { exact: true }).waitFor({ timeout: 120000 });
await page.waitForTimeout(600);
await page.setViewportSize({ width: 1440, height: 1000 });
await shot("4-agent");
await page.goto(`${base}/console`, { waitUntil: "networkidle" });
await page.waitForTimeout(800);
await shot("5-royalty-console");
await page.goto(`${base}/console/studio`, { waitUntil: "networkidle" });
await page.waitForTimeout(4000);
await shot("6-ag-studio");
await page.goto(`${base}/patterns/pat_astro_bunny`, { waitUntil: "networkidle" });
await shot("7-pattern-lineage");
await page.goto(`${base}/eval`, { waitUntil: "networkidle" });
await shot("8-accuracy");
const lic = await page.evaluate(async () => (await (await fetch("/api/checkout/license", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ patternId: "pat_astro_bunny", units: 12, itemPriceCents: 4000, maker: { id: "mkr_ana" } }) })).json()));
await page.goto(lic.approveUrl);
await page.getByRole("button", { name: "Pay now" }).click();
await page.waitForURL(/licenses\/lic_/);
await page.waitForLoadState("networkidle");
await shot("3-license-receipt", true);
await b.close();
console.log("ok");
