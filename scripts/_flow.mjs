import { chromium } from "playwright-core";
const out = process.argv[2];
const b = await chromium.launch({ channel: "msedge", headless: true });
const page = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
const errs = []; page.on("pageerror", e => errs.push(e.message));
await page.goto("http://localhost:3000/snap", { waitUntil: "networkidle" });
await page.getByRole("button", { name: "Astronaut bunny" }).click();
await page.getByText("License to sell").waitFor({ timeout: 60000 });
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/flow1_match.png`, fullPage: true });
await page.getByRole("button", { name: /with PayPal/ }).click();
await page.waitForURL(/sim\/paypal/);
await page.screenshot({ path: `${out}/flow2_paypal.png` });
await page.getByRole("button", { name: "Pay now" }).click();
await page.waitForURL(/licenses\/lic_/);
await page.waitForLoadState("networkidle");
await page.screenshot({ path: `${out}/flow3_license.png`, fullPage: true });
const licUrl = page.url();
await page.goto(licUrl.replace(/\?.*/, "").replace("/licenses/", "/t/") + "-1");
await page.screenshot({ path: `${out}/flow4_tag.png`, fullPage: true });
await page.goto("http://localhost:3000/agent", { waitUntil: "networkidle" });
await page.getByRole("button", { name: "Run agent" }).click();
await page.getByText("Answer", { exact: true }).waitFor({ timeout: 120000 });
await page.waitForTimeout(600);
await page.screenshot({ path: `${out}/flow5_agent.png`, fullPage: true });
await page.goto("http://localhost:3000/offers", { waitUntil: "networkidle" });
await page.getByRole("button", { name: /Look-alike/ }).click();
await page.getByRole("button", { name: "Check & draft offer" }).click();
await page.getByText(/Draft ready|not confident/).waitFor({ timeout: 120000 });
await page.getByRole("button", { name: /Approve & send/ }).first().click();
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}/flow6_offers.png`, fullPage: true });
console.log("done", licUrl, errs);
await b.close();
